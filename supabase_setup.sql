-- 6. RPC for Atomic Order Placement
CREATE OR REPLACE FUNCTION place_order(
  p_total NUMERIC,
  p_tax NUMERIC,
  p_discount NUMERIC,
  p_payment_method TEXT,
  p_user_id UUID,
  p_items JSONB
) RETURNS UUID AS $$
DECLARE
  v_order_id BIGINT;
  v_receipt_id UUID;
  v_item RECORD;
BEGIN
  -- 1. Insert Order
  INSERT INTO orders (total, tax, discount, payment_method, user_id)
  VALUES (p_total, p_tax, p_discount, p_payment_method, p_user_id)
  RETURNING id INTO v_order_id;

  -- 2. Insert Order Items and Update Stock
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(id BIGINT, quantity INTEGER, price NUMERIC)
  LOOP
    -- Insert Item
    INSERT INTO order_items (order_id, product_id, quantity, price)
    VALUES (v_order_id, v_item.id, v_item.quantity, v_item.price);

    -- Update Stock
    UPDATE products
    SET stock = stock - v_item.quantity
    WHERE id = v_item.id AND stock >= v_item.quantity;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient stock for product ID %', v_item.id;
    END IF;
  END LOOP;

  -- 3. Create Receipt
  v_receipt_id := gen_random_uuid();
  INSERT INTO receipts (id, order_id, type, status)
  VALUES (v_receipt_id, v_order_id, 'customer', 'digital_only');

  RETURN v_receipt_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 7. AUTH TRIGGER: Automatically create a profile in the 'users' table when a new user signs up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.users (id, username, role)
  VALUES (new.id, new.email, 'owner');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger the function every time a user is created in auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
