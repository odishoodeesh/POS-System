-- RPC for Stock Management
-- This function ensures stock doesn't go negative and handles concurrency
CREATE OR REPLACE FUNCTION decrement_stock(row_id BIGINT, amount INTEGER)
RETURNS void AS $$
BEGIN
  UPDATE products
  SET stock = stock - amount
  WHERE id = row_id AND stock >= amount;
  
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Insufficient stock for product ID %', row_id;
  END IF;
END;
$$ LANGUAGE plpgsql;

-- RPC for Atomic Order Placement
-- This handles order creation, item insertion, stock decrement, and receipt generation in one transaction
CREATE OR REPLACE FUNCTION place_order(
  p_total NUMERIC,
  p_tax NUMERIC,
  p_discount NUMERIC,
  p_payment_method TEXT,
  p_user_id BIGINT,
  p_items JSONB
) RETURNS UUID AS $$
DECLARE
  v_order_id BIGINT;
  v_receipt_id UUID;
  v_item RECORD;
BEGIN
  -- 1. Insert Order
  INSERT INTO orders (total, tax, discount, payment_method, user_id)
  VALUES (p_total, p_tax, p_discount, p_payment_method, p_user_id)
  RETURNING id INTO v_order_id;

  -- 2. Insert Order Items and Update Stock
  FOR v_item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(id BIGINT, quantity INTEGER, price NUMERIC)
  LOOP
    -- Insert Item
    INSERT INTO order_items (order_id, product_id, quantity, price)
    VALUES (v_order_id, v_item.id, v_item.quantity, v_item.price);

    -- Update Stock
    UPDATE products
    SET stock = stock - v_item.quantity
    WHERE id = v_item.id AND stock >= v_item.quantity;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient stock for product ID %', v_item.id;
    END IF;
  END LOOP;

  -- 3. Create Receipt
  v_receipt_id := gen_random_uuid();
  INSERT INTO receipts (id, order_id, type, status)
  VALUES (v_receipt_id, v_order_id, 'customer', 'digital_only');

  -- 4. Create Receipt Tax
  INSERT INTO receipt_taxes (receipt_id, tax_name, rate, amount)
  VALUES (v_receipt_id, 'VAT', 10, p_tax);

  RETURN v_receipt_id;
END;
$$ LANGUAGE plpgsql;
